import { useEffect, useState } from 'react';
import { useApp } from '../store';
import { FolderOpen, Clock, RefreshCw, ChevronDown, ChevronUp } from 'lucide-react';
import { formatTime } from '../types';

export default function Incidents() {
  const { incidents, alerts, events, refreshIncidents, refreshAlerts, refreshEvents } = useApp();
  const [loading, setLoading] = useState(false);
  const [expanded, setExpanded] = useState<string | null>(null);

  useEffect(() => {
    setLoading(true);
    Promise.allSettled([refreshIncidents(), refreshAlerts(), refreshEvents()]).finally(() => setLoading(false));
  }, []);

  const getRelatedAlerts = (incidentId: string) => alerts.filter(a => a.eventId);
  const getRelatedEvents = (incidentId: string) => events.slice(0, 5);

  const statusColor: Record<string, string> = {
    OPEN: 'text-red-700 bg-red-50 border-red-200',
    INVESTIGATING: 'text-blue-700 bg-blue-50 border-blue-200',
    RESOLVED: 'text-emerald-700 bg-emerald-50 border-emerald-200',
    CLOSED: 'text-slate-600 bg-slate-50 border-slate-200',
  };

  if (loading) return <div className="text-center py-16 text-slate-400">Loading incidents...</div>;

  return (
    <div className="space-y-5 animate-fade-in">
      <div className="flex items-center justify-between">
        <div>
          <h2 className="text-xl font-black text-slate-800 flex items-center gap-2">
            <FolderOpen className="h-5 w-5 text-orange-500" /> Incident Investigation
          </h2>
          <p className="text-xs text-slate-500 mt-0.5">{incidents.length} incidents · Click to open timeline</p>
        </div>
        <button onClick={() => { setLoading(true); Promise.allSettled([refreshIncidents()]).finally(() => setLoading(false)); }}
          className="flex items-center gap-2 px-3 py-2 rounded-lg border border-slate-200 bg-white text-slate-600 hover:bg-slate-50 text-xs font-semibold transition-colors">
          <RefreshCw className="h-3.5 w-3.5" /> Refresh
        </button>
      </div>

      {incidents.length === 0 ? (
        <div className="text-center py-16">
          <FolderOpen className="h-10 w-10 text-slate-300 mx-auto mb-3" />
          <p className="text-slate-500">No incidents found.</p>
          <p className="text-xs text-slate-400 mt-1">Incidents are auto-generated by multi-camera event correlation.</p>
        </div>
      ) : (
        <div className="space-y-3">
          {incidents.map(incident => {
            const isExp = expanded === incident.id;
            const relAlerts = getRelatedAlerts(incident.id);
            const relEvents = getRelatedEvents(incident.id);

            return (
              <div key={incident.id} className="bg-white border border-slate-200 rounded-xl overflow-hidden">
                <div className="flex items-center gap-3 px-4 py-3 cursor-pointer hover:bg-slate-50 transition-colors"
                  onClick={() => setExpanded(isExp ? null : incident.id)}>
                  <div className="flex-1 min-w-0">
                    <div className="flex items-center gap-2 flex-wrap">
                      <span className={`text-[10px] font-bold px-2 py-0.5 rounded border ${statusColor[incident.status] || 'text-slate-600 bg-slate-50 border-slate-200'}`}>
                        {incident.status}
                      </span>
                      <span className="text-[10px] font-mono text-slate-400">{incident.id.slice(0, 8)}...</span>
                    </div>
                    <p className="text-sm font-bold text-slate-800 mt-1">{incident.title}</p>
                    <p className="text-[10px] text-slate-400 mt-0.5 flex items-center gap-1">
                      <Clock className="h-3 w-3" /> {formatTime(incident.created_at)}
                    </p>
                  </div>
                  {isExp ? <ChevronUp className="h-4 w-4 text-slate-400" /> : <ChevronDown className="h-4 w-4 text-slate-400" />}
                </div>

                {/* Timeline */}
                {isExp && (
                  <div className="border-t border-slate-100 bg-slate-50 px-4 py-4">
                    <h4 className="text-[10px] font-black text-slate-500 uppercase tracking-widest mb-3 flex items-center gap-1.5">
                      <Clock className="h-3 w-3" /> Incident Timeline
                    </h4>

                    <div className="space-y-2 relative before:absolute before:left-[7px] before:top-2 before:bottom-2 before:w-px before:bg-slate-200">
                      {/* Incident created */}
                      <TimelineEntry
                        time={formatTime(incident.created_at)}
                        title="Incident Created"
                        detail={incident.title}
                        color="bg-orange-500"
                      />

                      {/* Related events */}
                      {relEvents.slice(0, 4).map(ev => (
                        <TimelineEntry
                          key={ev.id}
                          time={formatTime(ev.event_timestamp || ev.timestamp)}
                          title={ev.eventType}
                          detail={`Camera ${ev.cameraId} · Risk ${ev.riskScore}`}
                          color={ev.severity === 'CRITICAL' ? 'bg-red-500' : ev.severity === 'HIGH' ? 'bg-orange-500' : 'bg-amber-500'}
                        />
                      ))}

                      {/* Related alerts */}
                      {relAlerts.slice(0, 2).map(al => (
                        <TimelineEntry
                          key={al.id}
                          time={formatTime(al.createdAt)}
                          title={`Alert: ${al.title}`}
                          detail={`Severity: ${al.severity} · ${al.cameraId}`}
                          color="bg-red-500"
                        />
                      ))}
                    </div>

                    <div className="mt-4 pt-3 border-t border-slate-200 grid grid-cols-3 gap-3 text-center">
                      <div>
                        <p className="text-lg font-black text-slate-800">{relEvents.length}</p>
                        <p className="text-[9px] text-slate-400 uppercase font-bold">Events</p>
                      </div>
                      <div>
                        <p className="text-lg font-black text-slate-800">{relAlerts.length}</p>
                        <p className="text-[9px] text-slate-400 uppercase font-bold">Alerts</p>
                      </div>
                      <div>
                        <p className={`text-lg font-black ${incident.status === 'OPEN' ? 'text-red-600' : 'text-emerald-600'}`}>{incident.status}</p>
                        <p className="text-[9px] text-slate-400 uppercase font-bold">Status</p>
                      </div>
                    </div>
                  </div>
                )}
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}

function TimelineEntry({ time, title, detail, color }: { time: string; title: string; detail: string; color: string }) {
  return (
    <div className="flex items-start gap-3 pl-4 relative">
      <div className={`absolute left-0 w-3.5 h-3.5 rounded-full ${color} border-2 border-white shadow-sm -translate-x-0`} />
      <div>
        <p className="text-[9px] font-mono text-slate-400">{time}</p>
        <p className="text-xs font-bold text-slate-700">{title}</p>
        <p className="text-[10px] text-slate-500">{detail}</p>
      </div>
    </div>
  );
}
